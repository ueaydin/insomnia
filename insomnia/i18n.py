_current = "tr"


def language() -> str:
    return _current


def set_language(code: str) -> bool:
    global _current
    if code in TRANSLATIONS:
        _current = code
        return True
    return False


def texts() -> dict:
    return TRANSLATIONS[_current]


def t(key: str, **values) -> str:
    text = TRANSLATIONS[_current].get(key) or TRANSLATIONS["tr"].get(key, key)
    return text.format(**values) if values else text
